# ------------------------------------------------------------------
# panel_fns.R -- estimators, tests and data generators for chapter 10
#                (linear panels: FE, RE, FD and CRE).
#
# Notation (notation_v3.md 1.4 and 1.8): unit i = 1..N (a Nimbus merchant), period t (a month),
# T_i = number of observed periods of unit i (unbalanced panels). Model
#     Y_it = X_it' beta + alpha_i + eps_it,
# alpha_i the unit effect (Wooldridge writes c_i), eps_it the idiosyncratic error.
# Arguments, everywhere: y is the stacked Y_it; X is the n x k matrix of X_it (a vector is one
# column named "x"); id is the unit index i; t is the period index. Unit means are over the
# observed periods: Xbar_i = T_i^{-1} sum_t s_it X_it.
#
# Card functions:
#   within_tf(y, X, id)                  -> list(y, X): Ydd_it = Y_it - Ybar_i, Xdd_it = X_it - Xbar_i
#   mundlak_fit(y, X, id, time_fe, t)    -> list(b_x, b_xbar, V, ...): pooled OLS of Y_it on (1, X_it, Xbar_i)
#                                           [+ time dummies lambda_t and the unit averages of the time dummies]
#   hausman_classic(b_fe, V_fe, b_re, V_re) -> list(stat, df, p): the classical Hausman statistic H
#   hausman_robust(fit)                  -> list(stat, df, p): cluster-robust Wald of xi = 0 in mundlak_fit
#   lead_test(y, X, id, t)               -> p value of delta = 0 in the FE regression with X_{i,t+1}
# Helpers: fe_fit, re_fit, be_fit, fd_fit, fd_ar1, chamberlain_md, ht_iv, mg_fit, slope_test, ci95;
# data generators gen_P2 to gen_P7 (block P1 is generated by the inherited legacy code in 01_dgp.R).
# Cluster-robust variances are by unit, without a small-sample factor (CR0, plm's
# vcovHC(method = "arellano", type = "HC0"); the legacy 02_static_fe_re.R uses the same).
# ------------------------------------------------------------------

## ---- internal helpers ---------------------------------------------------------------------
.as_X <- function(X, nm = "x") {
  if (is.null(dim(X))) X <- matrix(as.numeric(X), ncol = 1L, dimnames = list(NULL, nm))
  X <- as.matrix(X)
  if (is.null(colnames(X))) colnames(X) <- paste0(nm, seq_len(ncol(X)))
  storage.mode(X) <- "double"
  X
}
.unit_index <- function(id) match(id, unique(id))                  # 1..G in order of appearance
.unit_means <- function(M, g) {                                       # G x k matrix of unit means (row j = unit j)
  M <- as.matrix(M)
  rowsum(M, g) / as.vector(rowsum(rep(1, nrow(M)), g))
}
# CR0 cluster-robust variance: bread * sum_g (Z_g' u_g)(Z_g' u_g)' * bread
.cl_vcov <- function(Z, u, g, bread = solve(crossprod(Z))) {
  S <- rowsum(Z * as.vector(u), g)
  V <- bread %*% crossprod(S) %*% bread
  dimnames(V) <- list(colnames(Z), colnames(Z))
  V
}
.wald <- function(b, V) {
  stat <- drop(crossprod(b, solve(V, b)))
  list(stat = stat, df = length(b), p = pchisq(stat, length(b), lower.tail = FALSE))
}

#' 95% interval est -/+ qnorm(0.975) se.
ci95 <- function(est, se) c(est - qnorm(0.975) * se, est + qnorm(0.975) * se)

## ---- card function: within transformation -------------------------------------------------
#' y is Y_it, X is X_it, id is i. Returns Ydd_it = Y_it - Ybar_i and Xdd_it = X_it - Xbar_i, the unit
#' means taken over the T_i observed periods of each unit (works for unbalanced panels).
within_tf <- function(y, X, id) {
  X <- .as_X(X); g <- .unit_index(id)
  m <- .unit_means(cbind(y, X), g)[g, , drop = FALSE]
  Xd <- X - m[, -1, drop = FALSE]; colnames(Xd) <- colnames(X)
  list(y = as.numeric(y) - m[, 1], X = Xd)
}

## ---- FE, RE, between and FD fits ------------------------------------------------------------
#' Fixed effects (within) estimator beta_hat_FE: pooled OLS of Ydd_it on Xdd_it (Wooldridge 2010 §10.5).
#' V is the cluster-robust variance (CR0, §10.5.4 eq. 10.59); V_classic = sigma2_eps (Xdd'Xdd)^{-1} with
#' sigma2_eps = SSR / (n - G - k) (FE.3, eq. 10.56); both equal plm's. resid are the within residuals.
fe_fit <- function(y, X, id) {
  X <- .as_X(X); g <- .unit_index(id); w <- within_tf(y, X, id); Xd <- w$X
  A <- solve(crossprod(Xd)); b <- drop(A %*% crossprod(Xd, w$y)); names(b) <- colnames(X)
  e <- drop(w$y - Xd %*% b)
  n <- length(e); G <- max(g); k <- ncol(X)
  s2 <- sum(e^2) / (n - G - k)
  V_classic <- s2 * A; dimnames(V_classic) <- list(colnames(X), colnames(X))
  list(b = b, V = .cl_vcov(Xd, e, g, A), V_classic = V_classic, sigma2_eps = s2, resid = e, n = n, G = G)
}

#' Between estimator beta_hat_BE: OLS of Ybar_i on (1, Xbar_i), one row per unit. V_classic as plm's.
be_fit <- function(y, X, id) {
  X <- .as_X(X); g <- .unit_index(id)
  m <- .unit_means(cbind(y, X), g)
  Z <- cbind("(Intercept)" = 1, m[, -1, drop = FALSE]); colnames(Z) <- c("(Intercept)", colnames(X))
  A <- solve(crossprod(Z)); b <- drop(A %*% crossprod(Z, m[, 1])); names(b) <- colnames(Z)
  e <- m[, 1] - drop(Z %*% b)
  s2 <- sum(e^2) / (nrow(Z) - ncol(Z))
  V <- s2 * A; dimnames(V) <- list(colnames(Z), colnames(Z))
  list(b = b, V_classic = V, ssr = sum(e^2), N = nrow(Z))
}

#' Random effects estimator beta_hat_RE as FGLS with the Swamy-Arora variance components (plm's default),
#' balanced panels only. varphi is the quasi-demeaning parameter
#'     varphi = 1 - sqrt(sigma2_eps / (sigma2_eps + T sigma2_alpha))       (Wooldridge 2010 §10.7.2 writes lambda),
#' and RE = pooled OLS of Y_it - varphi Ybar_i on (1 - varphi, X_it - varphi Xbar_i) (eqs. 10.78 to 10.81).
#' sigma2_eps = SSR_within / (n - G - k); T sigma2_alpha + sigma2_eps = T SSR_between / (G - k - 1).
#' V_classic = s2 times the inverse of the quasi-demeaned cross-product (valid under RE.3), s2 = SSR of the
#' quasi-demeaned regression / (n - k - 1), as plm's vcov(); V = cluster-robust (CR0).
re_fit <- function(y, X, id) {
  X <- .as_X(X); g <- .unit_index(id); Ti <- tabulate(g)
  if (length(unique(Ti)) != 1L) stop("re_fit: balanced panels only (use plm for unbalanced RE)")
  TT <- Ti[1]; k <- ncol(X); G <- max(g)
  fe <- fe_fit(y, X, id); be <- be_fit(y, X, id)
  s2e <- fe$sigma2_eps
  s21 <- TT * be$ssr / (G - k - 1)
  s2a <- (s21 - s2e) / TT
  varphi <- 1 - sqrt(s2e / s21)
  m <- .unit_means(cbind(y, X), g)[g, , drop = FALSE]
  ys <- as.numeric(y) - varphi * m[, 1]
  Z <- cbind("(Intercept)" = 1 - varphi, X - varphi * m[, -1, drop = FALSE]); colnames(Z) <- c("(Intercept)", colnames(X))
  A <- solve(crossprod(Z)); b <- drop(A %*% crossprod(Z, ys)); names(b) <- colnames(Z)
  e <- ys - drop(Z %*% b)
  V_classic <- sum(e^2) / (length(e) - ncol(Z)) * A; dimnames(V_classic) <- list(colnames(Z), colnames(Z))
  list(b = b, V_classic = V_classic, V = .cl_vcov(Z, e, g, A), varphi = varphi,
       sigma2_alpha = s2a, sigma2_eps = s2e, T = TT)
}

#' First-difference estimator beta_hat_FD: pooled OLS of Delta Y_it on (1, Delta X_it) over consecutive
#' observed periods (Wooldridge 2010 §10.6; intercept as in plm's model = "fd"). V is cluster-robust (CR0).
#' resid, rid and rt are the FD residuals and their unit and period, for fd_ar1().
fd_fit <- function(y, X, id, t) {
  X <- .as_X(X); o <- order(id, t); y <- as.numeric(y)[o]; X <- X[o, , drop = FALSE]; id <- id[o]; t <- t[o]
  n <- length(y); k <- which(id[-1] == id[-n] & t[-1] == t[-n] + 1) + 1L
  dy <- y[k] - y[k - 1]; dX <- X[k, , drop = FALSE] - X[k - 1, , drop = FALSE]
  Z <- cbind("(Intercept)" = 1, dX); colnames(Z) <- c("(Intercept)", colnames(X))
  A <- solve(crossprod(Z)); b <- drop(A %*% crossprod(Z, dy)); names(b) <- colnames(Z)
  e <- dy - drop(Z %*% b)
  list(b = b, V = .cl_vcov(Z, e, .unit_index(id[k]), A), resid = e, rid = id[k], rt = t[k])
}

#' AR(1) coefficient rho of the FD residuals (Wooldridge 2010 §10.6.3, eq. 10.71): pooled OLS of e_it on
#' (1, e_{i,t-1}), cluster-robust se. Under FD.3 (random-walk errors) rho = 0; under FE.3 (serially
#' uncorrelated errors) rho = -0.5. p_zero tests rho = 0, p_half tests rho = -0.5.
fd_ar1 <- function(fit) {
  e <- fit$resid; id <- fit$rid; t <- fit$rt; n <- length(e)
  k <- which(id[-1] == id[-n] & t[-1] == t[-n] + 1) + 1L
  Z <- cbind(1, e[k - 1]); A <- solve(crossprod(Z)); b <- drop(A %*% crossprod(Z, e[k]))
  u <- e[k] - drop(Z %*% b)
  se <- sqrt(.cl_vcov(Z, u, .unit_index(id[k]), A)[2, 2])
  list(rho = b[2], se = se, p_zero = 2 * pnorm(-abs(b[2] / se)), p_half = 2 * pnorm(-abs((b[2] + 0.5) / se)),
       n = length(k))
}

## ---- card function: Mundlak (CRE) regression ------------------------------------------------
#' Pooled OLS of Y_it on (1, X_it, Xbar_i), Xbar_i = T_i^{-1} sum_t s_it X_it over the observed periods
#' (Mundlak 1978; Wooldridge 2010 §10.7.3 eq. 10.88; alpha_i = xi_0 + Xbar_i' xi + a_i).
#' b_x is beta_hat (= beta_hat_FE exactly, balanced or not), b_xbar is xi_hat (= beta_hat_BE - beta_hat_FE in a
#' balanced panel), V is the cluster-robust (by unit, CR0) variance of all coefficients, coef the full vector.
#' time_fe = TRUE adds period dummies lambda_t and the unit averages of the period dummies; then b_x equals
#' two-way FE exactly in balanced and unbalanced panels (Wooldridge 2019; in a balanced panel the averaged
#' dummies are constants and drop out). Needs t. Columns that are exactly collinear (the averaged dummies of
#' a balanced panel) are dropped and listed in `dropped`.
mundlak_fit <- function(y, X, id, time_fe = FALSE, t = NULL) {
  X <- .as_X(X); g <- .unit_index(id)
  Xbar <- .unit_means(X, g)[g, , drop = FALSE]; colnames(Xbar) <- paste0("xbar_", colnames(X))
  Z <- cbind("(Intercept)" = 1, X, Xbar)
  if (isTRUE(time_fe)) {
    if (is.null(t)) stop("mundlak_fit: time_fe = TRUE needs the period index t")
    lev <- sort(unique(t))[-1]
    D <- outer(t, lev, "==") * 1; colnames(D) <- paste0("t_", lev)
    Dbar <- .unit_means(D, g)[g, , drop = FALSE]; colnames(Dbar) <- paste0("tbar_", lev)
    Z <- cbind(Z, D, Dbar)
  }
  q <- qr(Z, tol = 1e-9)
  keep <- sort(q$pivot[seq_len(q$rank)])
  core <- c("(Intercept)", colnames(X), colnames(Xbar))
  if (!all(match(core, colnames(Z)) %in% keep)) stop("mundlak_fit: X or Xbar is collinear")
  dropped <- colnames(Z)[-keep]
  Z <- Z[, keep, drop = FALSE]
  A <- solve(crossprod(Z)); coef <- drop(A %*% crossprod(Z, y)); names(coef) <- colnames(Z)
  e <- as.numeric(y) - drop(Z %*% coef)
  list(b_x = coef[colnames(X)], b_xbar = coef[colnames(Xbar)], V = .cl_vcov(Z, e, g, A), coef = coef,
       n = length(e), G = max(g), dropped = dropped)
}

## ---- card functions: Hausman tests -----------------------------------------------------------
#' Classical Hausman statistic H = (b_fe - b_re)' (V_fe - V_re)^{-1} (b_fe - b_re), chi^2 with df = dim
#' (Wooldridge 2010 §10.7.3 eq. 10.86; valid under RE.1 to RE.3). b_fe is beta_hat_FE, V_fe its
#' non-robust variance; b_re, V_re the same for beta_hat_RE (time-varying coefficients only). Equals plm::phtest.
hausman_classic <- function(b_fe, V_fe, b_re, V_re) {
  d <- as.numeric(b_fe) - as.numeric(b_re)
  .wald(d, as.matrix(V_fe) - as.matrix(V_re))
}

#' Robust (Mundlak) Hausman test: cluster-robust Wald test of xi = 0, fit from mundlak_fit (Wooldridge 2010
#' §10.7.3, after eq. 10.88; Arellano 1993). Valid without RE.3.
hausman_robust <- function(fit) {
  nm <- names(fit$b_xbar)
  .wald(fit$b_xbar, fit$V[nm, nm, drop = FALSE])
}

## ---- card function: lead test of strict exogeneity ------------------------------------------
#' FE regression Y_it = X_it' beta + X_{i,t+1}' delta + alpha_i + eps_it on the observations whose next period
#' is observed (Wooldridge 2010 §10.7.1, p. 325); cluster-robust Wald test of delta = 0, chi^2 with df = k.
#' Returns the p value; attributes stat, df, delta (delta_hat) and se.
lead_test <- function(y, X, id, t) {
  X <- .as_X(X); o <- order(id, t); y <- as.numeric(y)[o]; X <- X[o, , drop = FALSE]; id <- id[o]; t <- t[o]
  n <- length(y); has_lead <- c(id[-1] == id[-n] & t[-1] == t[-n] + 1, FALSE)
  Xl <- rbind(X[-1, , drop = FALSE], NA); colnames(Xl) <- paste0(colnames(X), "_lead")
  k <- which(has_lead)
  f <- fe_fit(y[k], cbind(X[k, , drop = FALSE], Xl[k, , drop = FALSE]), id[k])
  dn <- colnames(Xl)
  w <- .wald(f$b[dn], f$V[dn, dn, drop = FALSE])
  structure(w$p, stat = w$stat, df = w$df, delta = f$b[dn], se = sqrt(diag(f$V)[dn]), n = length(k))
}

## ---- Chamberlain's method by minimum distance -------------------------------------------------
#' Chamberlain (1982) correlated random effects, alpha_i = xi_0 + sum_t X_it' xi_t + a_i (Wooldridge 2010 §11.1.2,
#' eqs. 11.5 to 11.10; Wooldridge writes lambda_t). Balanced panels. Step 1: the reduced form, OLS of Y_it on
#' (1, X_i1, ..., X_iT) for each t, gives pi_hat (T (1 + T k) coefficients) with a cluster-robust variance
#' V_pi (by unit). Step 2: optimal minimum distance, pi = H theta with theta = (xi_0, beta, xi_1, ..., xi_T):
#' theta_hat = (H' V_pi^{-1} H)^{-1} H' V_pi^{-1} pi_hat (chapter 7's MD). stat is the overidentification
#' statistic (pi_hat - H theta_hat)' V_pi^{-1} (pi_hat - H theta_hat), chi^2 with (T - 1)(1 + T k) - k df:
#' a test of strict exogeneity together with the linear projection.
chamberlain_md <- function(y, X, id, t) {
  X <- .as_X(X); k <- ncol(X); o <- order(id, t)
  y <- as.numeric(y)[o]; X <- X[o, , drop = FALSE]; id <- id[o]; t <- t[o]
  lev <- sort(unique(t)); TT <- length(lev); N <- length(unique(id))
  if (length(y) != N * TT || any(tabulate(.unit_index(id)) != TT)) stop("chamberlain_md: balanced panels only")
  Y <- matrix(y, N, TT, byrow = TRUE)
  Xw <- do.call(cbind, lapply(seq_len(TT), function(s) {
    m <- X[t == lev[s], , drop = FALSE]; colnames(m) <- paste0(colnames(X), "_t", lev[s]); m
  }))
  Z <- cbind(1, Xw); m <- ncol(Z)
  Q <- solve(crossprod(Z)); Pi <- Q %*% crossprod(Z, Y); E <- Y - Z %*% Pi
  pi_hat <- as.vector(Pi)                                              # (pi_1', ..., pi_T')'
  ZQ <- Z %*% Q
  Psi <- do.call(cbind, lapply(seq_len(TT), function(s) ZQ * E[, s])) # row i: (Q z_i e_i1, ..., Q z_i e_iT)
  V_pi <- crossprod(Psi)
  p <- 1 + k + TT * k
  H <- matrix(0, m * TT, p)
  for (s in seq_len(TT)) {
    r0 <- (s - 1) * m
    H[r0 + 1, 1] <- 1
    for (r in seq_len(TT)) for (j in seq_len(k)) {
      row <- r0 + 1 + (r - 1) * k + j
      H[row, 1 + k + (r - 1) * k + j] <- 1
      if (r == s) H[row, 1 + j] <- 1
    }
  }
  Wt <- solve(V_pi)
  V_th <- solve(crossprod(H, Wt %*% H))
  th <- drop(V_th %*% crossprod(H, Wt %*% pi_hat))
  r <- pi_hat - drop(H %*% th)
  stat <- drop(crossprod(r, Wt %*% r)); df <- m * TT - p
  xi <- matrix(th[(2 + k):p], TT, k, byrow = TRUE)
  list(beta = setNames(th[2:(1 + k)], colnames(X)), se = setNames(sqrt(diag(V_th))[2:(1 + k)], colnames(X)),
       xi = if (k == 1L) drop(xi) else xi, theta = th, V = V_th, stat = stat, df = df,
       p = pchisq(stat, df, lower.tail = FALSE))
}

## ---- Hausman-Taylor as instrumental variables ----------------------------------------------------
#' Hausman and Taylor (1981), Wooldridge 2010 §11.3 eqs. 11.29 to 11.34: Y_it = X_1it' beta_1 + X_2it' beta_2
#' + W_i' gamma + alpha_i + eps_it, X_1 uncorrelated with alpha_i, X_2 and the time-invariant W_i correlated with
#' it. Given the quasi-demeaning parameter varphi, 2SLS of Y_it - varphi Ybar_i on (1 - varphi, X_1it - varphi
#' Xbar_1i, X_2it - varphi Xbar_2i, (1 - varphi) W_i) with instruments (1, Xdd_1it, Xdd_2it, Xbar_1i)
#' (chapter 9's IV; plm's inst.method = "baltagi"). Order condition: dim(X_1) >= dim(W).
ht_iv <- function(y, X1, X2, W, id, varphi) {
  X1 <- .as_X(X1, "x1"); X2 <- .as_X(X2, "x2"); W <- .as_X(W, "w"); g <- .unit_index(id)
  R <- cbind(X1, X2, W)
  m <- .unit_means(cbind(y, R), g)[g, , drop = FALSE]
  ys <- as.numeric(y) - varphi * m[, 1]
  Rs <- cbind("(Intercept)" = 1 - varphi, R - varphi * m[, -1, drop = FALSE])
  colnames(Rs) <- c("(Intercept)", colnames(R))
  Xd <- within_tf(y, cbind(X1, X2), id)$X
  Zi <- cbind(1, Xd, .unit_means(X1, g)[g, , drop = FALSE])
  Rh <- Zi %*% solve(crossprod(Zi), crossprod(Zi, Rs))               # first-stage fitted values
  coef <- drop(solve(crossprod(Rh, Rs), crossprod(Rh, ys))); names(coef) <- colnames(Rs)
  list(coef = coef, first_stage = Rh)
}

## ---- random slopes ------------------------------------------------------------------------------
#' Mean-group estimator of the average slope beta = E[b_i]: the average of the unit-by-unit OLS slopes
#' (plm::pvcm, model = "within"), se = sd / sqrt(N). One regressor; units need T_i >= 2 with variation in X.
mg_fit <- function(y, X, id) {
  X <- .as_X(X); if (ncol(X) != 1L) stop("mg_fit: one regressor")
  g <- .unit_index(id); w <- within_tf(y, X, id)
  b <- as.vector(rowsum(w$X[, 1] * w$y, g) / rowsum(w$X[, 1]^2, g))
  list(est = mean(b), se = sd(b) / sqrt(length(b)), slopes = b)
}

#' Test of correlated random slopes (Wooldridge 2010 §11.7.4): FE regression of Y_it on X_it and
#' X_it (Z_i - mean Z), Z a unit-level variable (one value per row, centred at its mean over rows);
#' cluster-robust Wald test that the interaction coefficients are zero.
slope_test <- function(y, X, id, Z) {
  X <- .as_X(X); zc <- as.numeric(Z) - mean(Z)
  XZ <- X * zc; colnames(XZ) <- paste0(colnames(X), "_x_z")
  f <- fe_fit(y, cbind(X, XZ), id)
  w <- .wald(f$b[colnames(XZ)], f$V[colnames(XZ), colnames(XZ), drop = FALSE])
  c(w, list(coef = f$b))
}

## ---- data generators (blocks P2 to P7; P1 is the inherited legacy gen_static in 01_dgp.R) ----------
## Every generator returns one row per merchant-month, sorted by id then t. Columns ending in _true are
## simulation truth, not observable data. Y is monthly GMV in thousands of USD, X is monthly promotion
## spend in hundreds of USD (P4: x1 is the Nimbus Fulfilment share in tens of percentage points).

.panel_index <- function(N, T) list(id = rep(seq_len(N), each = T), t = rep(seq_len(T), times = N))
.ar1 <- function(N, T, rho) {                      # stationary AR(1) with unit variance, N x T
  u <- matrix(0, N, T); u[, 1] <- rnorm(N)
  if (T > 1) for (s in 2:T) u[, s] <- rho * u[, s - 1] + rnorm(N, 0, sqrt(1 - rho^2))
  u
}

#' P2: the same promotions and the same monthly shocks e_it under two error laws: eps_iid_it = e_it
#' (FE.3) and the random walk eps_rw_it = e_i1 + ... + e_it (FD.3).
gen_P2 <- function(P) {
  N <- P$N; T <- P$T; ix <- .panel_index(N, T); id <- ix$id
  alpha <- rnorm(N, 0, P$alpha_sd)
  x <- P$x_mean + P$x_alpha * alpha[id] + as.vector(t(.ar1(N, T, P$rho_x)))
  e <- matrix(rnorm(N * T, 0, P$sigma_e), N, T)
  eps_iid <- as.vector(t(e)); eps_rw <- as.vector(apply(e, 1, cumsum))
  data.frame(id, t = ix$t, x,
             y_iid = P$mu0 + P$beta * x + alpha[id] + eps_iid,
             y_rw = P$mu0 + P$beta * x + alpha[id] + eps_rw,
             alpha_true = alpha[id], eps_iid_true = eps_iid, eps_rw_true = eps_rw)
}

#' P3: feedback. Promotions respond to last month's shock: X_it = x_mean + x_alpha alpha_i + feedback eps_{i,t-1}
#' + u_it (eps_i0 is a pre-sample month), so X_{i,t+1} is correlated with eps_it and strict exogeneity fails.
gen_P3 <- function(P) {
  N <- P$N; T <- P$T; ix <- .panel_index(N, T); id <- ix$id
  alpha <- rnorm(N, 0, P$alpha_sd)
  e <- matrix(rnorm(N * (T + 1), 0, P$sigma_e), N, T + 1)          # column 1 is month 0
  u <- matrix(rnorm(N * T, 0, P$x_sd), N, T)
  x <- P$x_mean + P$x_alpha * alpha + P$feedback * e[, 1:T, drop = FALSE] + u
  eps <- e[, 2:(T + 1), drop = FALSE]
  x <- as.vector(t(x)); eps <- as.vector(t(eps))
  data.frame(id, t = ix$t, x, y = P$mu0 + P$beta * x + alpha[id] + eps, alpha_true = alpha[id], eps_true = eps)
}

#' P4: Hausman-Taylor. W_i = 1 for a Nimbus Verified (certified) merchant, a time-invariant regressor
#' correlated with alpha_i; x1 (Nimbus Fulfilment share) depends on the distance to a warehouse (mu1_i),
#' not on alpha_i, and its unit mean predicts certification; x2 (promotion spend) is correlated with alpha_i.
gen_P4 <- function(P) {
  N <- P$N; T <- P$T; ix <- .panel_index(N, T); id <- ix$id
  alpha <- rnorm(N, 0, P$alpha_sd); mu1 <- rnorm(N); v <- rnorm(N)
  w <- as.integer(P$w_mu * mu1 + P$w_alpha * alpha + v > P$w_cut)
  x1 <- P$x1_mean + P$x1_mu * mu1[id] + rnorm(N * T, 0, P$x1_sd)
  x2 <- P$x2_mean + P$x2_alpha * alpha[id] + rnorm(N * T, 0, P$x2_sd)
  eps <- rnorm(N * T, 0, P$sigma_e)
  y <- P$mu0 + P$beta1 * x1 + P$beta2 * x2 + P$gamma * w[id] + alpha[id] + eps
  data.frame(id, t = ix$t, x1, x2, w = w[id], y, alpha_true = alpha[id], mu1_true = mu1[id], eps_true = eps)
}

#' P5 and P5b: random slopes b_i. X_it = mu_i + s_i u_it, s_i the merchant's within-merchant SD of promotion
#' spend (a type drawn from s_types with s_probs). design "within_sd" (P5): b_i = avg_slope + kappa (s_i^2 -
#' E[s^2]) + eta_i, slopes correlated with the within variation; design "level" (P5b): b_i = avg_slope +
#' kappa (mu_i - mu_mean) + eta_i, slopes correlated with the level Xbar_i only.
gen_P5 <- function(P) {
  N <- P$N; T <- P$T; ix <- .panel_index(N, T); id <- ix$id
  alpha <- rnorm(N, 0, P$alpha_sd)
  mu <- P$mu_mean + P$mu_alpha * alpha + rnorm(N, 0, P$mu_sd)
  s <- sample(P$s_types, N, replace = TRUE, prob = P$s_probs)
  eta <- rnorm(N, 0, P$eta_sd)
  Es2 <- sum(P$s_probs * P$s_types^2)
  b <- switch(P$design,
              within_sd = P$avg_slope + P$kappa * (s^2 - Es2) + eta,
              level = P$avg_slope + P$kappa * (mu - P$mu_mean) + eta,
              stop("gen_P5: design must be within_sd or level"))
  x <- mu[id] + s[id] * rnorm(N * T)
  eps <- rnorm(N * T, 0, P$sigma_e)
  data.frame(id, t = ix$t, x, y = P$mu0 + b[id] * x + alpha[id] + eps, b_true = b[id], s_true = s[id],
             mu_true = mu[id], alpha_true = alpha[id], eps_true = eps)
}

#' P6: a balanced panel and two attrition rules (absorbing: a merchant that leaves never returns; month 1 is
#' always observed). s_alpha: from month 2 an active merchant leaves with probability
#' pnorm(haz0 + haz_alpha alpha_i) (selection on alpha_i, Wooldridge 2010 Assumption 19.8 holds).
#' s_eps: a merchant leaves in the first month t >= 2 whose GMV Y_it falls below the floor; that month and
#' later months are not observed (selection on the shock eps_it through Y_it, Assumption 19.8 fails).
gen_P6 <- function(P) {
  N <- P$N; T <- P$T; ix <- .panel_index(N, T); id <- ix$id
  alpha <- rnorm(N, 0, P$alpha_sd)
  x <- P$x_mean + P$x_alpha * alpha[id] + rnorm(N * T)
  eps <- rnorm(N * T, 0, P$sigma_e)
  y <- P$mu0 + P$beta * x + alpha[id] + eps
  leave <- matrix(runif(N * T) < pnorm(P$haz0 + P$haz_alpha * alpha), N, T); leave[, 1] <- FALSE
  low <- matrix(y < P$floor, N, T, byrow = TRUE); low[, 1] <- FALSE
  stay <- function(m) as.vector(apply(m, 1, function(v) as.integer(cumsum(v) == 0)))
  data.frame(id, t = ix$t, x, y, alpha_true = alpha[id], eps_true = eps, s_alpha = stay(leave), s_eps = stay(low))
}

#' P7: RE.1 holds (alpha_i mean-independent of X_i), RE.3 fails: sd(alpha_i | X_i) = alpha_base + alpha_slope
#' |Xbar_i - x_mean|, and eps_it = (eps_base + eps_slope |X_it - x_mean|) e_it with e_it a stationary AR(1)
#' (rho_e). X_it = x_mean + mu_i + u_it, u_it a stationary AR(1) (rho_x).
gen_P7 <- function(P) {
  N <- P$N; T <- P$T; ix <- .panel_index(N, T); id <- ix$id
  mu <- rnorm(N, 0, P$mu_sd)
  x <- P$x_mean + mu[id] + as.vector(t(.ar1(N, T, P$rho_x)))
  xbar <- colMeans(matrix(x, T, N))
  alpha <- (P$alpha_base + P$alpha_slope * abs(xbar - P$x_mean)) * rnorm(N)
  eps <- (P$eps_base + P$eps_slope * abs(x - P$x_mean)) * as.vector(t(.ar1(N, T, P$rho_e)))
  data.frame(id, t = ix$t, x, y = P$mu0 + P$beta * x + alpha[id] + eps, alpha_true = alpha[id], eps_true = eps)
}
